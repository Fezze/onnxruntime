  static bool SchemaMatches(const ONNX_NAMESPACE::OpSchema& schema, Kind kind) {
    const char* name = kind == Kind::kLeaky ? "LeakyRelu" : "GreaterOrEqual";
    if (schema.Name() != name || !schema.domain().empty() || schema.SinceVersion() != 16 ||
        &schema != ONNX_NAMESPACE::OpSchemaRegistry::Schema(name, 20, "") ||
        !schema.has_type_and_shape_inference_function() || schema.has_data_propagation_function() ||
        !schema.HasFunction() || schema.HasContextDependentFunction() ||
        !schema.context_dependent_function_opset_versions().empty()) {
      return false;
    }
    const auto versions = schema.function_opset_versions();
    if (versions.size() != 1 || versions[0] != 16) return false;
    if (kind == Kind::kGreaterOrEqual) return schema.attributes().empty();
    if (schema.attributes().size() != 1) return false;
    const auto alpha = schema.attributes().find("alpha");
    return alpha != schema.attributes().end() && alpha->second.name == "alpha" &&
           alpha->second.type == ONNX_NAMESPACE::AttributeProto::FLOAT && !alpha->second.required &&
           alpha->second.default_value.SerializeAsString() == kAlphaDefault;
  }

  static bool CurrentMatches(const ONNX_NAMESPACE::NodeProto& original,
                             const ONNX_NAMESPACE::NodeProto& current) {
    ONNX_NAMESPACE::NodeProto original_base(original);
    ONNX_NAMESPACE::NodeProto current_base(current);
    original_base.clear_attribute();
    current_base.clear_attribute();
    if (original_base.SerializeAsString() != current_base.SerializeAsString() ||
        original.attribute_size() != current.attribute_size()) {
      return false;
    }
    for (const auto& attribute : original.attribute()) {
      const ONNX_NAMESPACE::AttributeProto* match = nullptr;
      for (const auto& candidate : current.attribute()) {
        if (candidate.name() == attribute.name()) {
          if (match != nullptr) return false;
          match = &candidate;
        }
      }
      if (match == nullptr || match->SerializeAsString() != attribute.SerializeAsString()) return false;
    }
    return true;
  }

  static bool ProposeLeaky(const ONNX_NAMESPACE::TypeProto& input, ONNX_NAMESPACE::TypeProto& proposal) {
    if (!input.has_tensor_type() || !input.tensor_type().has_elem_type() ||
        input.tensor_type().elem_type() != ONNX_NAMESPACE::TensorProto_DataType_FLOAT) {
      return false;
    }
    auto* output = proposal.mutable_tensor_type();
    output->set_elem_type(ONNX_NAMESPACE::TensorProto_DataType_FLOAT);
    // Matches propagateShapeAndTypeFromFirstInput without exposing a context:
    // absent shape remains absent, distinct from a shape-present scalar.
    if (input.tensor_type().has_shape()) *output->mutable_shape() = input.tensor_type().shape();
    return true;
  }

  static bool ProposeGreater(const ONNX_NAMESPACE::TypeProto& left,
                             const ONNX_NAMESPACE::TypeProto& right,
                             ONNX_NAMESPACE::TypeProto& proposal) {
    if (!left.has_tensor_type() || !right.has_tensor_type()) return false;
    const auto& a = left.tensor_type();
    const auto& b = right.tensor_type();
    if (a.elem_type() != ONNX_NAMESPACE::TensorProto_DataType_FLOAT ||
        b.elem_type() != ONNX_NAMESPACE::TensorProto_DataType_FLOAT || !a.has_shape() || !b.has_shape() ||
        a.shape().dim_size() != 2 || b.shape().dim_size() != 2 ||
        !a.shape().dim(0).has_dim_value() || a.shape().dim(0).dim_value() != 1 ||
        !b.shape().dim(1).has_dim_value() || b.shape().dim(1).dim_value() != 1) {
      return false;
    }
    auto* output = proposal.mutable_tensor_type();
    output->set_elem_type(ONNX_NAMESPACE::TensorProto_DataType_BOOL);
    // Exact original1327 descriptor broadcast: [1,D] with [T,1]. Copy only
    // metadata; no comparison of tensor elements or generic broadcast evaluator.
    auto* shape = output->mutable_shape();
    *shape->add_dim() = b.shape().dim(0);
    *shape->add_dim() = a.shape().dim(1);
    return true;
  }

  static Result MatchAndPropose(size_t source_index,
                                const ONNX_NAMESPACE::NodeProto& owner_original,
                                const ONNX_NAMESPACE::NodeProto& current,
                                const ONNX_NAMESPACE::OpSchema& selected,
                                const SlotTypes& input_types,
                                const SlotLiterals& initializers,
                                gsl::span<const ONNX_NAMESPACE::AttributeProto* const> owner_default_origins,
                                ONNX_NAMESPACE::TypeProto& scratch) {
    const auto* recipe = Find(source_index);
    if (recipe == nullptr) return Result::kNotMatched;
    // All28 alpha attributes are originally present, including the one equal
    // to the schema default; original1327 has no attributes or defaults.
    if (!owner_default_origins.empty() || owner_original.SerializeAsString() != recipe->node_wire ||
        !SchemaMatches(selected, recipe->kind) || !CurrentMatches(owner_original, current)) {
      return Result::kRefused;
    }
    for (size_t slot = 0; slot < input_types.size(); ++slot) {
      if (initializers[slot] != nullptr || input_types[slot] == &scratch ||
          (input_types[slot] == nullptr) != recipe->types[slot].empty() ||
          (input_types[slot] != nullptr && input_types[slot]->SerializeAsString() != recipe->types[slot])) {
        return Result::kRefused;
      }
    }
    ONNX_NAMESPACE::TypeProto proposal;
    const bool proposed = recipe->kind == Kind::kLeaky
                              ? ProposeLeaky(*input_types[0], proposal)
                              : ProposeGreater(*input_types[0], *input_types[1], proposal);
    if (!proposed) return Result::kRefused;
    scratch.Swap(&proposal);
    return Result::kProposed;
  }
